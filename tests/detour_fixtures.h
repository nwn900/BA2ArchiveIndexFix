inline std::vector<std::uint8_t> Stub(const Site& site, std::uintptr_t helper,
                                      std::uintptr_t continuation) {
    auto result = site.stub;
    const auto helper64 = static_cast<std::uint64_t>(helper);
    const auto continuation64 = static_cast<std::uint64_t>(continuation);
    std::memcpy(result.data() + site.helper_offset, &helper64, sizeof(helper64));
    std::memcpy(result.data() + site.return_offset, &continuation64, sizeof(continuation64));
    return result;
}

